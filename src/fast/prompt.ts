export function buildFastUser(req: FastRequest, baziPillars?: string): string {
  const sex = req.gender === "male" ? "男宝宝" : "女宝宝";
  const py = surnamePinyin(req.surname);
  const lines = [
    `给${req.surname}姓${sex}起 5 个双字名。姓读 ${py}。`,
    "每个 why 一句话、20 字以内。",
  ];
  // 这里刻意不把「这一场已经给过的名字」念给模型听：报整名或报用字都会让它
  // 逐个比对 / 逐字规避，实测单轮 14–31 秒、还偶发只返回 1 个可用名字。
  // 去重放在 run.ts 本地做（过滤掉重复的，够 3 个才用），零耗时。
  // 连姓的谐音也已经在 gate.ts 里用拼音做了，所以这里不再要求模型自己念一遍。
  if (baziPillars) {
    lines.push(
      `这个宝宝的四柱是：${baziPillars}。名字可以顺带呼应，但不要说天干地支、五行用神这类词，也别说「一定」「注定」——只作温和参考。`,
    );
  }
  lines.push("只输出 JSON。");
  return lines.join("\n");
}

/**
 * 单名补出处：只在「首推没出处」时兜底调一次。
 *
 * 一句话、一个字段、不许翻找——实测 2–3 秒返回；想不出就返回空，
 * 调用方留白。这条不参与主链路，触发率约 20%。
 */
export function buildCitePrompt(givenName: string): { system: string; user: string } {
  return {
    system: "你是中文起名助手。只输出 JSON，推理不超过 40 字。",
    user: [
      `名字「${givenName}」出自哪一篇古籍？source 只能从这个清单里选：${SOURCE_CATALOG.join("、")}；piece 写具体篇名（如「周南·汉广」，不带括注）。`,
      "line 把你想引的那一句原样抄下来，这一句里这两个字要挨着出现。抄不准就整条留空。",
      "只想最有把握的那一个来源。想不出、或者要停下来翻找，就把三项都返回空字符串。不要编。",
      '输出：{"source":"","piece":"","line":""}',
    ].join("\n"),
  };
}
