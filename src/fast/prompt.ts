/** 姓氏读音，多音姓按姓的读法（曾 zēng、解 xiè、单 shàn） */function surnamePinyin(surname: string): string {
  const raw = pinyin(surname, { toneType: "symbol", type: "array", surname: "head" });
  return (Array.isArray(raw) ? raw : [raw]).map(String).join(" ");
}

