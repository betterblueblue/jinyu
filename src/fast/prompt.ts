/**
 * 精简版提示词。
 *
 * 2026-10-31 改过一版，实测数据（本机网关 opendesign/deepseek-v4.1-flash，沈姓女宝）：
 *
 * | | 旧版 | 现版 |
 * |---|---|---|
 * | 单次耗时（6 轮） | 2.6–10.5s，中位 5.6s | 5.2–13.6s，中位 6.5s |
 * | 出名字带出处 | 20/24（83%） | 23/24（96%） |
 * | why 写法 | 「静是娴静，姝是美好」逐字报义 | 「露水将干未干，清亮的那一刻」一句判断 |
 *
 * 两条实测结论，改之前先看：
 * 1. **推理必须限死，这是耗时的唯一开关**。只写「推理不超过 100 字」时，
 *    模型大约每 6 轮有 1 轮去逐条自查，推理 4800 字、单轮 26 秒；
 *    改成「推理里只写候选名字，不要写理由、不要写分析」后，6 轮全在 3.2–6.7 秒。
 * 2. **不要要求模型以「先想起原句、名字必须是原句里紧挨着的两个字」来取名**。
 *    它真会为每个名字回翻古籍，推理 4000–7500 字、单轮 22–28 秒。
 *    出处只在「有把握」时填，靠 src/fast/cite.ts 回原文核，核不到就留白。
 *
 * 4 个字段的理由：完整版每候选 10 个字段、单次 39 秒；这里 4 个字段，中位 6.5 秒。
 * 出处只给「书名 + 篇名」，原文由 cite.ts 回语料截，截出来一定是原文子串。
 *
 * 已知没解决（别以为能靠改提示词解决）：
 * - 模型只能给篇名，给不了「它想引的那一句」。所以「清和」会被截成楚辞
 *   「音晏衍兮要婬」、「书宁」被截成「诗书宁救眼前贫」——篇章对、句子不对。
 *   要彻底修，得让模型连原句一起给，再逐字核。
 * - 反复给的还是那几个名句名（令仪 / 知微 / 清越），因为「有把握的出处」本身就窄。
 *   要多样性得由调用方传入「本轮已经给过的名字」。
 */

