/**
 * 精简版提示词。
 *
 * 直播路线定了：模型现场出名字，3–5 秒。所以这份提示词的首要指标不是「写得多讲究」，
 * 而是「别让模型把预算花在复核上」。
 *
 * 耗时结构（2026-10-31 实测，本机网关 opendesign/deepseek-v4.1-flash，沈姓女宝）：
 *   总耗时 ≈ firstTok 1.1–1.9s + 推理字数/190 + 正文 0.7–2.3s
 *   firstTok 是网关自己的（89 token 零缓存也要 1.1 秒），改提示词动不了。
 *   3–5 秒的预算里推理只够 0–400 字，实测却到过 2806 字、单轮 20 秒。
 *
 * 2026-10-31 这一版删了什么、为什么：
 *   1. 删「连姓念一遍」：gate.ts 用拼音做了同音检查（王望、林临 现在拦得住），
 *      而且模型在这条上花的推理最多（沈默沈思沈重逐个念一遍）。
 *   2. 删 41 个烂大街名 + 26 个热门字两串清单：实测产出与这两串零交集、一次没触发，
 *      但模型每轮都要读一遍、再逐个候选比对。拦截留在 gate（L1 直接拒）+ run.ts（热门字排后）。
 *      如果删了以后热门字真的开始出现，在 gate 里加一行硬拦即可，不用把清单请回来。
 *   3. 删「候选之间不重复用字」：run.ts 的 dedupeChars 做，零耗时。
 *   4. 出处段 10 行并成 5 行：原来第 110 行「只给篇名也可以」和第 113 行「只想得起篇名就整条留空」
 *      自相矛盾，模型于是有时给句、有时不给。现在只有一条：三件一起给，或者三件全空。
 *   5. 删「五个名字的声调别全是一种」（第二轮实测）：这条是前面几条删完之后唯一剩下的推理来源。
 *      抓到的原始推理 537 字、从头到尾是「声调检查：知微阴平加阴平，平了，换知夏」。
 *      它的字面读法（五个名字调型别全一样）8 轮一次没触发；模型自己的读法（一个字里不许平平）
 *      把「知微」这种好名误杀。所以不搬进代码，直接删。
 *
 * 保留的是什么、为什么不能删：
 *   - 语域标尺 12 条 + 「不要景物拼贴、不要古人字号」这组反例：这是独特价值所在。
 *   - why 的写法和两个正例：直播大字只显示这一行，是观众唯一会念出来的字。
 *   - 出处逐字回核那几句：核不到就留白，比编一句强。
 *
 * 已知没解决（改提示词解决不了的）：
 * - 反复给的还是那几个名句名（令仪 / 知微）：靠 run.ts 的 recent 去重挡。
 *
 * 出处不再走「本地相邻兜底」（2026-10-31 第二轮实测）：
 * 那批兜底截出来的句子，近一半不能当众念——两字隔着逗号（语宁 ← 不与华池语，宁将浴室论）、
 * 跨词（知夏 ← 曾不知夏之为丘兮）、原文就带缺字方块（书宁 ← □万卷诗书宁愤穷）。
 * 现在是：模型给了原句、逐字核过才展示，核不到就留白。宁可少一条出处，不念一句错话。
 */

